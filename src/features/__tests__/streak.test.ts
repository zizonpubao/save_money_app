import { computeStreak, streakLabel } from '@/src/features/streak';

describe('computeStreak (M4 연속 기록일)', () => {
  it('오늘까지 이어진 날 수를 센다', () => {
    expect(computeStreak(['2026-09-24', '2026-09-23', '2026-09-22'], '2026-09-24')).toBe(3);
  });

  it('오늘 기록이 아직 없어도 어제까지 이어졌으면 유지한다', () => {
    expect(computeStreak(['2026-09-23', '2026-09-22'], '2026-09-24')).toBe(2);
  });

  it('어제도 오늘도 없으면 0', () => {
    expect(computeStreak(['2026-09-22', '2026-09-21'], '2026-09-24')).toBe(0);
  });

  it('중간에 빠진 날이 있으면 그 앞에서 끊긴다', () => {
    expect(computeStreak(['2026-09-24', '2026-09-23', '2026-09-21', '2026-09-20'], '2026-09-24')).toBe(2);
  });

  it('빈 배열이면 0', () => {
    expect(computeStreak([], '2026-09-24')).toBe(0);
  });

  it('월 경계를 넘어 이어서 센다', () => {
    expect(computeStreak(['2026-10-01', '2026-09-30', '2026-09-29'], '2026-10-01')).toBe(3);
    // 오늘(10/1) 없음 → 어제(9/30)부터
    expect(computeStreak(['2026-09-30', '2026-09-29'], '2026-10-01')).toBe(2);
    expect(computeStreak(['2026-09-29'], '2026-10-01')).toBe(0);
  });

  it('해 경계와 순서·중복은 상관없다', () => {
    expect(computeStreak(['2025-12-31', '2026-01-01', '2026-01-01', '2025-12-30'], '2026-01-01')).toBe(3);
  });

  it('칩 글자는 "🔥 N일째"', () => {
    expect(streakLabel(5)).toBe('🔥 5일째');
  });
});
